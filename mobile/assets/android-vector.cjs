// Turns the logo into an Android vector drawable for the launcher icon, so it stays sharp at every size
// (@capacitor/assets renders the foreground PNG too small, and Android then scales it up and blurs it).
// Runs after capacitor-assets (npm run icons): writes drawable/ic_launcher_foreground_ikan.xml and points
// the adaptive icons at it.
const fs = require('fs'), path = require('path');
const { fish, COLORS } = require('./logo.cjs');
const FOREGROUND_SCALE = 0.72; // same as icon-foreground.png in make-icons.cjs

const res = path.join(__dirname, '..', 'android', 'app', 'src', 'main', 'res');
const svg = fish(FOREGROUND_SCALE, 512, 512);
const [, cx, cy, s, px, py] = svg.match(/translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)\) translate\(([-\d.]+) ([-\d.]+)\)/).map(Number);
const paths = [...svg.matchAll(/<path d="([^"]+)" stroke="([^"]+)" stroke-width="([^"]+)"\/>/g)]
  .map(([, d, color, w]) => `      <path android:pathData="${d}" android:strokeColor="${color}" android:strokeWidth="${w}"
          android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>`);
if (!paths.length) throw new Error('no paths found in the logo');

// The adaptive icon insets this layer by 16.7%, so the 1024 viewport is the visible area, as in icon-foreground.png.
// Group transform: (p - pivot) * scale + pivot + translate = (p - (px, py)) * s + (cx, cy)
const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/assets/android-vector.cjs from logo.cjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="72dp" android:height="72dp" android:viewportWidth="1024" android:viewportHeight="1024">
    <group android:pivotX="${-px}" android:pivotY="${-py}" android:scaleX="${s}" android:scaleY="${s}"
        android:translateX="${cx + px}" android:translateY="${cy + py}">
${paths.join('\n')}
    </group>
</vector>
`;
fs.mkdirSync(path.join(res, 'drawable'), { recursive: true });
fs.writeFileSync(path.join(res, 'drawable', 'ic_launcher_foreground_ikan.xml'), xml);

for (const f of ['ic_launcher.xml', 'ic_launcher_round.xml']) {
  const p = path.join(res, 'mipmap-anydpi-v26', f);
  const before = fs.readFileSync(p, 'utf8');
  const after = before.replace('@mipmap/ic_launcher_foreground', '@drawable/ic_launcher_foreground_ikan');
  if (!after.includes('@drawable/ic_launcher_foreground_ikan')) throw new Error('foreground not found in ' + f);
  fs.writeFileSync(p, after);
}
console.log('vector launcher icon written,', paths.length, 'paths, colours', COLORS.line, COLORS.letter);
